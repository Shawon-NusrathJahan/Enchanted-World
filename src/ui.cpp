void endFrame()
{
    mouse.pressed  = false;
    mouse.released = false;
}

float textWidth(const char* s, float px)
{
    const size_t n = std::strlen(s);
    return n ? (6.0f * n - 1.0f) * px : 0.0f;
}

void drawText(float x, float y, float px, const Color& c, const char* s, bool centered)
{
    if (centered) x -= textWidth(s, px) * 0.5f;
    for (int pass = 0; pass < 2; pass++)                    // pass 0 = drop shadow, pass 1 = text
    {
        const float ox = pass == 0 ? px * 0.7f : 0.0f, oy = pass == 0 ? -px * 0.7f : 0.0f;
        if (pass == 0) glColor4f(0.0f, 0.0f, 0.0f, 0.55f * c.a);
        else           glColor4f(c.r, c.g, c.b, c.a);
        glBegin(GL_QUADS);
        float cx = x;
        for (const char* p = s; *p; ++p, cx += 6.0f * px)
        {
            const Glyph* g = findGlyph(*p);
            for (int row = 0; row < 7; row++)
                for (int col = 0; col < 5; col++)
                    if (g->r[row][col] == '1')
                    {
                        const float x0 = cx + ox + col * px, y0 = y + oy + (6 - row) * px;
                        glVertex2f(x0, y0); glVertex2f(x0 + px, y0);
                        glVertex2f(x0 + px, y0 + px); glVertex2f(x0, y0 + px);
                    }
        }
        glEnd();
    }
}

bool hover(float cx, float cy, float r)
{
    if (!mouse.valid) return false;
    const float dx = mouse.x - cx, dy = mouse.y - cy;
    return dx * dx + dy * dy <= r * r;
}

bool backButton()
{
    const float cx = -WORLD_W + 0.11f, cy = 0.88f, r = 0.07f;
    const bool  hov = hover(cx, cy, r);
    buttonBase(cx, cy, r, hov);
    glColor4f(1.0f, 1.0f, 1.0f, 1.0f);
    thickLine(cx - 0.028f, cy, cx + 0.038f, cy, 0.016f);            // arrow shaft
    tri(cx - 0.046f, cy, cx - 0.004f, cy + 0.034f, cx - 0.004f, cy - 0.034f);   // arrow head
    if (hov) drawText(cx + r + 0.02f, cy - 0.02f, 0.0075f, rgb(1, 1, 1), "RESTART");
    return hov && mouse.pressed;
}

