"""gen_fontdata.py - converts TrueType glyph OUTLINES into src/fontdata.h

The game does not load font files at run time. Instead the outlines (straight
lines + quadratic Bezier curves, exactly as stored in the TrueType 'glyf'
table) are written into a C++ header. font.cpp then flattens the curves and
rasterises the polygons itself with a scan-line fill (see CG_ALGORITHMS.md).

Fonts (SIL Open Font License 1.1, see assets/fonts/):
  * Cinzel Decorative Bold  - the "Enchanted World" logo
  * Fredoka SemiBold        - every other text (HUD, labels, tooltips)

usage:  python3 tools/gen_fontdata.py <CinzelDecorative-Bold.ttf> <Fredoka[wdth,wght].ttf> > src/fontdata.h
"""
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen
from fontTools.varLib.instancer import instantiateVariableFont

class OpPen(BasePen):
    """records outlines as  M x y | L x y | Q cx cy x y | Z"""
    def __init__(self, glyphSet):
        super().__init__(glyphSet)
        self.ops = []
    def _moveTo(self, p):           self.ops.append((0, p))
    def _lineTo(self, p):           self.ops.append((1, p))
    def _qCurveToOne(self, c, p):   self.ops.append((2, c, p))
    def _curveToOne(self, c1, c2, p):   # cubic (not used by TrueType) -> approximate by two quadratics
        p0 = self._getCurrentPoint()
        m = ((p0[0] + 3*c1[0] + 3*c2[0] + p[0]) / 8, (p0[1] + 3*c1[1] + 3*c2[1] + p[1]) / 8)
        self.ops.append((2, ((p0[0]+c1[0])/2+(c1[0]-p0[0])/4, (p0[1]+c1[1])/2+(c1[1]-p0[1])/4), m))
        self.ops.append((2, ((c2[0]+p[0])/2+(c2[0]-p[0])/-4, (c2[1]+p[1])/2+(c2[1]-p[1])/-4), p))
    def _closePath(self):           self.ops.append((3,))
    def _endPath(self):             self.ops.append((3,))

def dump(name, font, chars):
    gs = font.getGlyphSet()
    cmap = font.getBestCmap()
    upm = font['head'].unitsPerEm
    hhea = font['hhea']
    data, table = [], []
    for ch in chars:
        g = cmap.get(ord(ch))
        if g is None:
            table.append((ord(ch), 0, 0, len(data))); continue
        pen = OpPen(gs)
        gs[g].draw(pen)
        start = len(data)
        for op in pen.ops:
            data.append(op[0])
            for pt in op[1:]:
                data.append(int(round(pt[0]))); data.append(int(round(pt[1])))
        table.append((ord(ch), gs[g].width, len(data) - start, start))
    out = []
    out.append(f"// {name}: units per em {upm}, ascent {hhea.ascent}, descent {hhea.descent}")
    out.append(f"constexpr int {name}_UPM = {upm}, {name}_ASC = {hhea.ascent}, {name}_DESC = {hhea.descent};")
    out.append(f"constexpr short {name}_OPS[] = {{")
    for i in range(0, len(data), 24):
        out.append("    " + ",".join(str(v) for v in data[i:i+24]) + ",")
    out.append("};")
    out.append(f"constexpr GlyphRec {name}_GLYPHS[] = {{")
    for c, adv, n, start in table:
        out.append(f"    {{{c}, {adv}, {start}, {n}}},")
    out.append("};")
    return "\n".join(out)

def main():
    deco = TTFont(sys.argv[1])
    ui = TTFont(sys.argv[2])
    if 'fvar' in ui:
        ui = instantiateVariableFont(ui, {"wght": 600, "wdth": 100})
    chars = "".join(chr(c) for c in range(32, 127))
    print("// fontdata.h - GENERATED by tools/gen_fontdata.py - do not edit by hand")
    print("// Glyph outlines from Cinzel Decorative Bold and Fredoka SemiBold (SIL Open Font License 1.1).")
    print("// Op stream: 0 = moveTo x y, 1 = lineTo x y, 2 = quadratic Bezier cx cy x y, 3 = close contour.")
    print("#ifndef FONTDATA_H\n#define FONTDATA_H\n")
    print("namespace fontdata\n{\n")
    print("struct GlyphRec { short code, advance; int start, count; };\n")
    print(dump("DECO", deco, chars))
    print()
    print(dump("UIF", ui, chars))
    print("\n}   // namespace fontdata\n\n#endif")

main()
